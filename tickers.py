CODE2NAME = dict(UNIVERSE)

# 指数・為替（分析はできるがスクリーニング対象外）
INDICES = {
    "日経平均": "^N225", "日経": "^N225", "TOPIX": "1306.T",
    "ドル円": "JPY=X", "ユーロ円": "EURJPY=X", "S&P500": "^GSPC",
    "ナスダック": "^IXIC", "NYダウ": "^DJI", "VIX": "^VIX",
}


def resolve(query):
    """入力（コード or 銘柄名）→ (yfinanceシンボル, 表示名)。見つからなければ (None, None)"""
    import re
    q = query.strip()
    if not q:
        return None, None
    qu = q.upper()
    if qu in CODE2NAME:
        return qu + ".T", CODE2NAME[qu]
    for name, sym in INDICES.items():
        if name in q or q == sym:
            return sym, name
    if re.fullmatch(r"[0-9][0-9A-Z]{3}", qu):
        return qu + ".T", qu  # ユニバース外でもコード直指定は許可
    if re.fullmatch(r"[0-9][0-9A-Z]{3}\.T", qu) or qu.startswith("^") or "=" in qu:
        return qu, qu
    hits = [(c, n) for c, n in UNIVERSE if q in n]
    if len(hits) >= 1:
        return hits[0][0] + ".T", hits[0][1]
    return None, None
